@Injectable({
  providedIn: 'root'
})
export class I18nService {
  private readonly storageKey = 'mini-shop-language';
  readonly language = signal<Language>('pt');

  constructor() {
    const savedLanguage = localStorage.getItem(this.storageKey) as Language | null;

    if (savedLanguage && ['pt', 'en', 'fr'].includes(savedLanguage)) {
      this.setLanguage(savedLanguage);
      return;
    }

    this.setLanguage('pt');
  }

  setLanguage(language: Language) {
    this.language.set(language);
    localStorage.setItem(this.storageKey, language);
    document.documentElement.lang = language;
  }

  translate(key: string) {
    return translations[this.language()][key] ?? translations.pt[key] ?? key;
  }
}
